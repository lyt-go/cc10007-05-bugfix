def _dataset(
    dataset_id: str,
    batch_id: str,
    version: str,
    status: str,
    source: dict[str, Any],
    members: list[dict[str, Any]],
    accuracy: float,
    generated_at: str,
    mode: str,
    note: str,
    previous: str | None,
    auditable: bool,
    eliminated: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    return {
        "数据集编号": dataset_id,
        "批次编号": batch_id,
        "数据集版本": version,
        "状态": status,
        "数据快照": source["数据快照"],
        "规则编号": source["规则材料"]["规则编号"],
        "规则版本": source["规则材料"]["规则版本"],
        "模型编号": source["模型材料"]["模型编号"],
        "模型版本": source["模型材料"]["模型版本"],
        "模型准确率": accuracy,
        "名单数": len(members),
        "成员": [dict(item) for item in members],
        "校验摘要": dataset_checksum(
            dataset_id, source, [str(item["用户编号"]) for item in members]
        ),
        "生成时间": generated_at,
        "生成方式": mode,
        "修复说明": note,
        "前序数据集": previous,
        "故障边界": source["故障边界"],
        "可审计": auditable,
        "来源材料": source,
        "消除错误": eliminated or [],
        "复核结论": "待复核" if status == "当前" else "已归档",
    }


def _member_rows(
    dataset_id: str,
    batch_id: str,
    version: str,
    members: list[dict[str, Any]],
    start_id: int,
    *,
    current: bool,
) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for offset, member in enumerate(members):
        row = {"id": start_id + offset, "批次编号": batch_id, "数据集编号": dataset_id,
               "数据集版本": version, "当前": current}
        row.update(member)
        rows.append(row)
    return rows


